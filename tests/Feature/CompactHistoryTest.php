<?php

namespace Tests\Feature;

use App\Models\Detection;
use App\Models\User;
use App\Services\Detections\MediaAnalysisReport;
use App\Services\Detections\ReportAnswer;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Http;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;

class CompactHistoryTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        Http::preventStrayRequests();
        config()->set('firebase.enabled', false);
        config()->set('services.media_calibration.enabled', false);
        $this->travelTo(Carbon::parse('2026-10-16 08:00:00', 'UTC'));
    }

    public function test_history_uses_claim_titles_owner_references_and_local_relative_dates(): void
    {
        $user = User::factory()->create();
        $other = User::factory()->create();
        $this->report($other, ['caption_text' => 'Private other-user claim']);
        $first = $this->report($user, ['caption_text' => 'An older assessment', 'analyzed_at' => now()->subDays(3), 'archived_at' => now()]);
        $yesterday = $this->report($user, ['caption_text' => 'Was this photo taken yesterday?', 'analyzed_at' => now()->subDay()]);
        $this->report($other);
        $today = $this->report($user, ['caption_text' => 'Is this image generated by AI or is it an authentic photograph from the original event?', 'fact_check_result' => $this->mediaResult(), 'verdict' => 'fake']);
        $snapshot = $today->fresh()->getRawOriginal();
        $response = $this->actingAs($user)->get(route('history'))->assertOk()->assertDontSee('Private other-user claim')
            ->assertDontSee('Fact check result')->assertSee('TG-03')->assertSee('Today')->assertSee('Yesterday')
            ->assertSee('Date range')->assertSee('Uncalibrated model output')
            ->assertViewHas('historyRows', fn ($rows) => $rows->first()['case'] === $today->caption_text
                && $rows->first()['report_reference'] === 'TG-03' && $rows->last()['report_reference'] === 'TG-02'
                && $rows->first()['date_label'] === 'Today' && $rows->last()['date_label'] === 'Yesterday');
        $this->assertSame($snapshot, $today->fresh()->getRawOriginal());
        $this->get(route('history', ['status' => 'archived']))->assertOk()
            ->assertViewHas('historyRows', fn ($rows) => $rows->sole()['report_reference'] === 'TG-01');

        if (getenv('TRUTHGUARD_COMPACT_HISTORY_BROWSER_FIXTURE')) {
            file_put_contents(storage_path('tmp-history-compact.html'), $response->getContent());
        }
        Http::assertNothingSent();
    }

    public static function scores(): array
    {
        return ['legacy only' => [null, 'Not available', false], 'raw model' => ['model', 'Model score: 99%', true],
            'calibrated fixture' => ['calibrated', 'Confidence: 82%', true], 'uncalibrated confidence rejected' => ['invalid', 'Not available', false]];
    }

    #[DataProvider('scores')]
    public function test_only_recorded_valid_percentages_are_shown(?string $type, string $label, bool $available): void
    {
        $user = User::factory()->create();
        $saved = $type ? $this->mediaResult() : null;
        if (in_array($type, ['calibrated', 'invalid'], true)) {
            $saved['score'] = ['type' => 'confidence', 'label' => 'Confidence', 'value' => .82,
                'validation' => $type === 'calibrated' ? 'calibrated' : 'uncalibrated',
                'method_version' => 'synthetic-rendering-fixture', 'explanation' => 'Rendering fixture only.'];
        }
        $this->report($user, ['fake_score' => 99, 'verdict' => 'fake', 'fact_check_result' => $saved]);
        $this->actingAs($user)->get(route('history'))->assertOk()
            ->assertViewHas('historyRows', fn ($rows) => $rows->sole()['confidence_display'] === $label
                && $rows->sole()['has_score'] === $available && $rows->sole()['confidence'] === null)
            ->assertDontSee('role="progressbar"', false)->assertDontSee('style="width: 99%', false);
        Http::assertNothingSent();
    }

    public function test_archive_is_owner_scoped_preserves_assessment_and_keeps_report_number(): void
    {
        $user = User::factory()->create();
        $report = $this->report($user, ['fact_check_result' => $this->mediaResult()]);
        $other = $this->report(User::factory()->create());
        $snapshot = $report->fresh()->only(['fact_check_result', 'media_path', 'caption_text', 'verdict', 'analyzed_at']);
        $this->actingAs($user)->patch(route('history.archive', $other))->assertNotFound();
        $this->assertNull($other->fresh()->archived_at);
        $this->patch(route('history.archive', $report), ['search' => 'Photo', 'sort' => 'oldest', 'status' => 'all'])
            ->assertRedirect(route('history', ['status' => 'all', 'search' => 'Photo', 'sort' => 'oldest']))
            ->assertSessionHas('status', 'history-archived');
        $report->refresh();
        $this->assertSame('user', $report->archive_reason);
        $this->assertEquals($snapshot, $report->only(array_keys($snapshot)));
        $archivedAt = $report->archived_at->toIso8601String();
        $this->travel(5)->minutes();
        $this->patch(route('history.archive', $report))->assertRedirect(route('history'));
        $this->assertSame($archivedAt, $report->fresh()->archived_at->toIso8601String());
        $this->get(route('history'))->assertOk()->assertViewHas('historyRows', fn ($rows) => $rows->isEmpty());
        $this->get(route('history', ['status' => 'archived']))->assertOk()
            ->assertViewHas('historyRows', fn ($rows) => $rows->sole()['report_reference'] === 'TG-01');
        Http::assertNothingSent();
    }

    private function report(User $user, array $values = []): Detection
    {
        return Detection::create(array_merge(['user_id' => $user->id, 'media_type' => 'image', 'source_kind' => 'upload',
            'source_url' => '/images/truthguard-logo.png', 'caption_text' => 'Photo claim to review', 'fake_score' => 90,
            'processing_status' => 'completed', 'verdict' => 'review', 'analyzed_at' => now()], $values));
    }

    private function mediaResult(): array
    {
        return ReportAnswer::complete(MediaAnalysisReport::result(['status' => 'completed', 'media_type' => 'image',
            'label' => 'fake', 'fake_probability' => .99, 'threshold' => .5, 'label_mapping' => ['real', 'fake'],
            'output_contract' => ['activation' => 'sigmoid', 'positive_class' => 'fake', 'binary_exclusive' => true]], ['status' => 'not_requested']));
    }
}
